import { Injectable } from '@nestjs/common';
import type { AiProvider } from './ai-provider.interface.js';
import type { AiPromptRequest, AiPromptResponse, StructuredCitation } from './ai.types.js';

@Injectable()
export class OfflineMockAiProvider implements AiProvider {
  readonly providerName = 'offline_mock';

  async generate(request: AiPromptRequest): Promise<AiPromptResponse> {
    const startTime = Date.now();

    if (request.instruction.includes('SIMULATE_AI_ERROR')) {
      throw new Error('Simulated upstream AI provider connection error');
    }

    const citations: StructuredCitation[] = [];
    if (request.instruction.includes('SIMULATE_HALLUCINATION')) {
      citations.push({
        sourceDocumentId: '00000000-0000-0000-0000-000000000000',
        documentTitle: 'NonExistentDoc.pdf',
        pageNumber: 99,
        quote: 'This is a completely fabricated quotation never appearing in any matter file.',
      });
    } else {
      for (const doc of request.contextDocuments) {
        citations.push({
          sourceDocumentId: doc.id,
          documentTitle: doc.title,
          pageNumber: 1,
          quote: doc.content.slice(0, 120).trim() || 'Referenced matter documentation extract.',
        });
      }
    }

    let generatedText = '';
    let confidenceNotes = 'Draft generated by offline mock legal assistant. Verify all citations against primary sources.';

    switch (request.feature) {
      case 'summarise_document':
        generatedText = `Document Summary: ${request.title}\n\n` +
          `Overview:\nThis matter document provides foundational evidence regarding the instructions. ` +
          `Key obligations, dates, and provisions have been extracted for fee earner appraisal.\n\n` +
          `Key Points:\n1. Primary subject matter confirmed.\n2. Identified counterparty and contractual dates.\n3. Procedural deadlines require supervisory notation.`;
        break;

      case 'draft_correspondence':
        generatedText = `Subject: In the Matter of Our Client - Update on Case Progress\n\n` +
          `Dear Client,\n\n` +
          `We write to provide you with a formal update concerning your matter. ` +
          `Having reviewed the recent documentation, we confirm that all preliminary procedural steps have been initiated.\n\n` +
          `Please find our initial review enclosed for your attention. We will contact you immediately upon receipt of the counterparty's response.\n\n` +
          `Yours sincerely,\nStass Legal Team`;
        break;

      case 'extract_chronology':
        generatedText = `### Chronology of Events — ${request.title}\n\n` +
          `| Date | Event Description | Actors | Source & Page | Citation Quote |\n` +
          `| :--- | :--- | :--- | :--- | :--- |\n` +
          `| **2024-01-15** | Initial contract execution and exchange | Claimant & Defendant | [Agreement.pdf] p. 1 | "The parties agree to the terms set forth herein." |\n` +
          `| **2024-06-30** | Notice of alleged breach dispatched | Claimant Solicitor | [Notice.pdf] p. 1 | "Formal notice is hereby given of breach." |\n\n` +
          `#### Chronology Notes\n- Verified against uploaded matter documentation.`;
        break;

      case 'review_clauses':
        generatedText = `Clause Comparison and Risk Appraisal:\n\n` +
          `1. Limitation of Liability: Standard commercial terms identified. Recommendation to verify monetary cap against firm guidelines.\n` +
          `2. Governing Law & Jurisdiction: Confirmed English Law with Exclusive Jurisdiction of Courts of England & Wales.\n` +
          `3. Termination Provisions: 30-day mutual notice clause present with cure period.`;
        break;
    }

    const promptTokens = Math.max(25, Math.ceil((request.instruction.length + request.contextDocuments.reduce((sum, d) => sum + d.content.length, 0)) / 4));
    const completionTokens = Math.max(50, Math.ceil(generatedText.length / 4));
    const latencyMs = Math.max(5, Date.now() - startTime);

    return {
      modelName: 'mock-legal-assistant-v1',
      generatedText,
      structuredCitations: citations,
      confidenceNotes,
      promptTokens,
      completionTokens,
      latencyMs,
    };
  }
}
