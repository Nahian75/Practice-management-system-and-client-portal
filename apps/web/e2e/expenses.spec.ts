import {expect,test} from './support/test';
import {signedInStaff} from './support/session';
import {openMatter} from './support/matters';
import {noAxeViolations,watchForCspViolations} from './support/checks';

test('records a receipt-backed expense, voids a mistake and bills the remaining expense once',async({page,request})=>{
 test.setTimeout(90_000);
 const violations=await watchForCspViolations(page);
 await signedInStaff(page,request,['partner','accounts']);
 const {account}=await(await page.request.get('/api/auth/session')).json() as {account:{id:string}};
 const today=(await(await page.request.get('/api/workspace/performance')).json() as {asOf:string}).asOf;
 const matter=await openMatter(page.request,account.id,[],{address:{line1:'22 Client Road',line2:null,town:'London',postcode:'SW1A 2AA',country:'GB'}});
 await page.goto(`/matters/${matter.id}`);
 await page.getByLabel('Title',{exact:true}).fill('Travel receipt');
 await page.getByLabel('File',{exact:true}).setInputFiles({name:'receipt.txt',mimeType:'text/plain',buffer:Buffer.from('Synthetic receipt for travel: GBP 10.03 net. No real client data.')});
 await page.getByRole('button',{name:'Add document',exact:true}).click();
 await expect(page.getByRole('row',{name:/Travel receipt/})).toBeVisible();
 await page.goto(`/finance/matters/${matter.id}`);
 const form=page.getByRole('form',{name:'Record an expense',exact:true});
 await form.getByLabel('Expense date',{exact:true}).fill(today);
 await form.getByLabel('Expense description',{exact:true}).fill('Travel for a client meeting');
 await form.getByLabel('Expense net amount in GBP',{exact:true}).fill('10.03');
 await form.getByLabel('Receipt (optional)',{exact:true}).selectOption({label:'Travel receipt — version 1'});
 await form.getByRole('button',{name:'Record expense',exact:true}).click();
 await expect(form.getByRole('status')).toHaveText('Expense recorded.');
 const expenses=page.getByRole('region',{name:'Expenses and disbursements',exact:true});
 await expect(expenses.getByRole('row',{name:/Travel for a client meeting/})).toContainText('Unbilled');
 await expect(expenses.getByRole('row',{name:/Travel for a client meeting/})).toContainText('Receipt version attached');
 await form.getByLabel('Expense date',{exact:true}).fill(today);
 await form.getByLabel('Expense description',{exact:true}).fill('Mistaken travel expense');
 await form.getByLabel('Expense net amount in GBP',{exact:true}).fill('5.00');
 await form.getByRole('button',{name:'Record expense',exact:true}).click();
 const mistake=expenses.getByRole('row',{name:/Mistaken travel expense/});
 await mistake.getByText('Void expense',{exact:true}).click();
 await mistake.getByLabel('Reason for void',{exact:true}).fill('Duplicate receipt recorded during review');
 await mistake.getByRole('button',{name:'Confirm void',exact:true}).click();
 await expect(mistake).toContainText('Voided');
 await noAxeViolations(page);
 const draft=page.getByRole('form',{name:'Start a draft bill',exact:true});
 await expect(draft.getByRole('option',{name:'Travel for a client meeting - GBP 10.03',exact:true})).toHaveCount(1);
 await expect(draft.getByRole('option',{name:'Mistaken travel expense - GBP 5.00',exact:true})).toHaveCount(0);
 await draft.getByLabel('Tax point',{exact:true}).fill(today);
 await draft.getByLabel('Payment due',{exact:true}).fill(today);
 await draft.getByLabel('Firm name',{exact:true}).fill('Stass Test Firm');
 await draft.getByLabel('Address line 1',{exact:true}).fill('1 Example Street');
 await draft.getByLabel('Town or city',{exact:true}).fill('London');
 await draft.getByLabel('VAT registration number (when taxable)',{exact:true}).fill('GB123456789');
 await draft.getByLabel('Recorded expense (optional)',{exact:true}).selectOption({label:'Travel for a client meeting - GBP 10.03'});
 await expect(draft.getByLabel('Net amount in GBP',{exact:true})).toHaveValue('10.03');
 await expect(draft.getByLabel('Net amount in GBP',{exact:true})).toBeDisabled();
 await draft.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.waitForURL(/\/finance\/bill-drafts\//);
 const edit=page.getByRole('form',{name:'Edit draft bill',exact:true});
 await edit.getByRole('button',{name:'Save draft',exact:true}).click();
 await expect(edit.getByRole('status')).toHaveText('Draft saved.');
 await page.getByRole('button',{name:'Issue fixed bill',exact:true}).click();
 await page.waitForURL(new RegExp(`/finance/matters/${matter.id}`));
 await expect(page.getByRole('row',{name:/Travel for a client meeting/})).toContainText('Billed');
 const saved=await(await page.request.get(`/api/matters/${matter.id}/expenses`)).json() as {expenses:{description:string;billId:string|null}[]};
 const charged=saved.expenses.find(e=>e.description==='Travel for a client meeting')!;
 const bill=await(await page.request.get(`/api/bills/${charged.billId}`)).json() as {gross:string;lines:{expenseEntryId:string|null}[]};
 expect(bill.gross).toBe('12.04');expect(bill.lines).toHaveLength(1);expect(bill.lines[0]!.expenseEntryId).toBeTruthy();
 await noAxeViolations(page);expect(violations).toEqual([]);
});
