import {expect,test} from './support/test';
import {signedInStaff,apiSessionFor} from './support/session';
import {openMatter} from './support/matters';

test('keeps one timer across reload and tabs and records its reviewed time once',async({page,request,context})=>{
 const accounts=await apiSessionFor(request,['accounts']);
 await signedInStaff(page,request,['partner']);
 const {account}=await(await page.request.get('/api/auth/session')).json() as {account:{id:string}};
 const today=(await(await page.request.get('/api/workspace/performance')).json() as {asOf:string}).asOf;
 expect((await accounts.api.post('/api/finance/rates',{data:{accountId:account.id,hourlyRate:'120.00',effectiveFrom:today}})).status()).toBe(201);
 const matter=await openMatter(page.request,account.id);
 await page.goto('/activities');
 await expect(page.getByRole('button',{name:'Start timer',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Start timer',exact:true}).click();
 await expect(page.getByRole('button',{name:'Pause timer',exact:true})).toBeEnabled();
 await expect(page.getByRole('timer')).not.toHaveText('00:00:00');
 await page.reload();
 await expect(page.getByRole('button',{name:'Pause timer',exact:true})).toBeEnabled();
 const second=await context.newPage();
 await second.goto('/activities');
 await expect(second.getByRole('button',{name:'Pause timer',exact:true})).toBeEnabled();
 await second.getByRole('button',{name:'Pause timer',exact:true}).click();
 await expect(page.getByRole('button',{name:'Start timer',exact:true})).toBeEnabled();
 await second.getByLabel('Timer options',{exact:true}).click();
 await second.getByRole('link',{name:'Record 1 minute',exact:true}).click();
 await expect(second).toHaveURL(/timerId=.*timerRevision=/);
 await second.getByRole('combobox',{name:/^Matter/}).selectOption(matter.id);
 await second.getByRole('button',{name:'Continue',exact:true}).click();
 const form=second.getByRole('form',{name:'Record time',exact:true});
 await expect(form.getByLabel('Minutes',{exact:true})).toHaveValue('1');
 const [year,month,day]=today.split('-');
 await form.getByLabel('Day',{exact:true}).fill(String(Number(day)));
 await form.getByLabel('Month',{exact:true}).fill(String(Number(month)));
 await form.getByLabel('Year',{exact:true}).fill(year!);
 await form.getByLabel('Work description',{exact:true}).fill('Reviewed client instructions using the shared timer.');
 await form.getByRole('button',{name:'Record time',exact:true}).click();
 await expect(form.getByRole('status')).toHaveText('Time recorded.');
 await expect(form.getByRole('button',{name:'Record time',exact:true})).toBeDisabled();
 await expect(second.getByRole('timer')).toHaveText('00:00:00');
 const saved=await(await page.request.get(`/api/matters/${matter.id}/time-entries`)).json() as {timeEntries:{minutes:number}[]};
 expect(saved.timeEntries).toHaveLength(1);expect(saved.timeEntries[0]!.minutes).toBe(1);
 await page.reload();
 await expect(page.getByRole('timer')).toHaveText('00:00:00');
 await second.close();
 await accounts.api.dispose();
});
